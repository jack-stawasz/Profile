# Fourier terms of the home banner's signature path, so the page draws its epicycles without sampling or a DFT
import json
import os
import re

import numpy as np
from svgpathtools import parse_path
# -------------------------------------------------------------

# ==================================================
# Settings
# ==================================================
HERE      = os.path.dirname(os.path.abspath(__file__))
HTML_PATH = os.path.join(HERE, "..", "..", "home.html")
OUT_PATH  = os.path.join(HERE, "..", "signature-fourier.js")

SAMPLE_COUNT = 600     # points along the path, and so the number of terms
DIGITS       = 6       # significant digits kept per number

# ==================================================
# Sampling
# ==================================================
def __readPath():
    html = open(HTML_PATH, encoding="utf-8").read()
    d = re.search(r'id="svgPath"\s+d="([^"]+)"', html, re.S).group(1)
    return parse_path(" ".join(d.split()))

# Evenly spaced by arc length, like the browser's getPointAtLength; pen lifts (M) add no length
def __sample(path, n):
    lengths = np.array([seg.length() for seg in path])
    starts = np.concatenate(([0], np.cumsum(lengths)))
    points = []
    for s in np.arange(n) / n * starts[-1]:
        i = min(np.searchsorted(starts, s, side="right") - 1, len(path) - 1)
        seg = path[i]
        points.append(seg.point(seg.ilength(s - starts[i]) if lengths[i] > 0 else 0))
    return np.array(points)

# ==================================================
# Fourier Terms
# ==================================================
z = __sample(__readPath(), SAMPLE_COUNT)
z -= z.mean()

# X_k = (1/N) Σ z_n e^{-2πikn/N}, so z(t) = Σ X_k e^{ikt} passes through sample n at t = 2πn/N
X = np.fft.fft(z) / SAMPLE_COUNT
k = np.fft.fftfreq(SAMPLE_COUNT, 1 / SAMPLE_COUNT).astype(int)
order = np.argsort(-np.abs(X))

def __round(v):
    return float(f"{v:.{DIGITS}g}")

terms = [[int(k[i]), __round(np.abs(X[i])), __round(np.angle(X[i]))] for i in order]
bounds = {"x0": z.real.min(), "x1": z.real.max(), "y0": z.imag.min(), "y1": z.imag.max()}

# ==================================================
# Output
# ==================================================
with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by pages/banner/sources/signature_fourier.py from the svgPath in pages/home.html; "
        "do not edit.\n")
    f.write("// terms: [frequency, amplitude, phase], largest first, in path units about the path's centroid.\n")
    f.write("const SIGNATURE_FOURIER = {\n")
    f.write(f"  bounds: {json.dumps({key: __round(v) for key, v in bounds.items()})},\n")
    f.write("  terms: [\n")
    for i in range(0, len(terms), 3):
        f.write("    " + ", ".join(json.dumps(t) for t in terms[i:i + 3]) + ",\n")
    f.write("  ],\n};\n")
print(f"{len(terms)} terms written to {os.path.normpath(OUT_PATH)}")
